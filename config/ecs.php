<?php

return [

    /*
    |--------------------------------------------------------------------------
    | テストログイン（DB不要）
    |--------------------------------------------------------------------------
    | true のとき、コードに埋め込んだテスト用アカウント（App\Support\TestAccounts）で
    | DBを使わずにログインできる。DBが無い／未接続のテスト環境で画面確認するための機能。
    |
    | ⚠⚠ 本番公開の直前に、ここの既定を false に変える（または .env に false を書く）。
    |
    |   いま既定を true のままにしている理由（2026-08-05 baba判断）：
    |   テストサーバーで社内フィードバックをもらっている最中で、体験ボタンが消えると
    |   確認が止まってしまうため。「消すのはぎりぎりに」との指示で据え置き。
    |
    |   ⚠ 既定が true ＝ 本番の .env に ECS_TEST_LOGIN=false と書き忘れただけで
    |     「誰でも固定パスワードで Administrator として入れる」状態になる。
    |     書き忘れが即事故になるので、本番移行のチェックリストの最上位に入れること。
    */
    'test_login' => env('ECS_TEST_LOGIN', true),

    /*
    |--------------------------------------------------------------------------
    | 見本（ダミー）データを入れてよいか
    |--------------------------------------------------------------------------
    | true のとき、php artisan db:seed で架空の社員・スタッフ・案件（DemoSeeder）が入る。
    | false なら本物の初期データ（必要アサイン人数リスト）だけが入る。
    |
    | 未設定のときは「本番（APP_ENV=production）以外なら true」に倒れる。
    | ＝本番サーバーだけ、.env に何も書かなくても見本データが入らない。
    | 自分のPCとテストサーバーは今までどおり見本が入る（確認が止まらないように）。
    |
    | 本番で一時的に見本を入れたい場合だけ ECS_SEED_DEMO=true と書く（通常は不要）。
    */
    'seed_demo' => env('ECS_SEED_DEMO', env('APP_ENV') !== 'production'),

];
