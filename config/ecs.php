<?php

return [

    /*
    |--------------------------------------------------------------------------
    | テストログイン（DB不要）
    |--------------------------------------------------------------------------
    | true のとき、コードに埋め込んだテスト用アカウント（App\Support\TestAccounts）で
    | DBを使わずにログインできる。DBが無い／未接続のテスト環境で画面確認するための機能。
    |
    | ★2026-08-24 baba判断＝既定を false にした（体験ボタンを閉じた）。
    |   テストサーバーが本番サーバーになり、本物のアカウントを配り終わったため。
    |
    |   なぜ「既定を false」にするのか：
    |   以前は既定が true だったので、.env に ECS_TEST_LOGIN=false と書き忘れただけで
    |   「URLを知っている人が、画面に書かれた固定パスワードで Administrator として入れる」
    |   状態になっていた（＝書き忘れが即事故）。
    |   既定を false にすると、.env に何も書かなければ閉じている＝安全側に倒れる。
    |
    |   自分のPCで体験ボタンを使いたいときは、.env に次の1行を書く：
    |     ECS_TEST_LOGIN=true
    |   （自動テストは phpunit.xml で true にしてある）
    |
    |   ⚠ 本番の .env には絶対に書かないこと。
    */
    'test_login' => env('ECS_TEST_LOGIN', false),

    /*
    |--------------------------------------------------------------------------
    | 見本（ダミー）データを入れてよいか
    |--------------------------------------------------------------------------
    | true のとき、php artisan db:seed で架空の社員・スタッフ・案件（DemoSeeder）が入る。
    | false なら本物の初期データ（必要アサイン人数リスト）だけが入る。
    |
    | ★2026-08-24 既定を false にした（テストログインと同じ考え方）。
    |
    |   以前は「APP_ENV が production 以外なら true」だった。しかし本番サーバーの
    |   APP_ENV が production になっているかを確認できていないため、その状態で
    |   php artisan db:seed（本物の初期データ＝必要アサイン人数リストを入れるのに必要）を
    |   流すと、架空の社員・案件まで本番に入ってしまう恐れがあった。
    |   ＝「書かなければ入らない」に倒す。
    |
    |   自分のPCで見本データを使いたいときは、.env に次の1行を書く：
    |     ECS_SEED_DEMO=true
    */
    'seed_demo' => env('ECS_SEED_DEMO', false),

];
