    /** 都道府県として正しい名前か。 */
    public static function isValid(mixed $name): bool
    {
        return in_array(trim((string) $name), self::ALL, true);
    }

    /**
     * 隣の県だけ（自分は含まない）。
     * ⚠ 片側だけ書かれていても両方向で効くようにそろえる。
     *
     * @return array<int, string>
     */
    public static function neighbors(mixed $name): array
    {
        $name = trim((string) $name);
        if (! self::isValid($name)) {
            return [];
        }

        $out = self::NEXT[$name] ?? [];
        // 逆向きに書かれているぶんを拾う（書き漏れで片方向だけになるのを防ぐ）。
        foreach (self::NEXT as $other => $list) {
            if ($other !== $name && in_array($name, $list, true)) {
                $out[] = $other;
            }
        }

        return array_values(array_unique($out));
    }

    /**
     * その県＋隣の県（自分が先頭）。体験先さがしの「場所の条件」に使う。
     *
     * @return array<int, string>
     */
    public static function withNeighbors(mixed $name): array
    {
        $name = trim((string) $name);
        if (! self::isValid($name)) {
            return [];
        }

        return array_merge([$name], self::neighbors($name));
    }
