    /**
     * 見出し行から「ECSの正式名 → 列の位置」の対応表を作る。
     *
     * @param  list<string>  $header  CSVの1行目
     * @return array{map: array<string, int>, unmapped: list<string>}
     *         map＝正式名→位置／unmapped＝取り込まなかった見出し（画面で知らせる用）
     */
    public static function resolve(array $header): array
    {
        // 別名 → 正式名 の辞書（照合用に正規化したキーで持つ）
        $lookup = [];
        foreach (self::ALIASES as $canonical => $names) {
            foreach ($names as $name) {
                $lookup[self::normKey($name)] = $canonical;
            }
        }

        $map = [];
        $unmapped = [];

        foreach ($header as $i => $raw) {
            $label = trim((string) $raw);
            if ($label === '') {
                continue;
            }
            $canonical = $lookup[self::normKey($label)] ?? null;
            if ($canonical === null) {
                $unmapped[] = $label;
                continue;
            }
            // 同じ意味の列が2つある場合は、先に出てきた方を使う。
            if (! isset($map[$canonical])) {
                $map[$canonical] = $i;
            }
        }

        return ['map' => $map, 'unmapped' => $unmapped];
    }

    /**
     * 開催日を 'Y-m-d' に整える。読めない場合は空文字（＝呼び出し側でエラーにする）。
     *
     * 受け付ける形：2026-07-20／2026/7/20／2026.7.20／2026年7月20日／
     *              「7/20(火)」のような曜日つき（年が無いものは読めない＝空を返す）／
     *              Excelのシリアル値（例 46208）
     */
    public static function normalizeDate(string $value): string
    {
        $v = trim($value);
        if ($v === '') {
            return '';
        }

        // 曜日のカッコ書きを外す（7/20(火) → 7/20）
        $v = preg_replace('/[（(][^）)]*[）)]/u', '', $v);
        $v = trim($v);

        // Excelのシリアル値（1900年基準・整数）。1〜60000くらいを日付とみなす。
        if (preg_match('/^\d+(\.\d+)?$/', $v) && (float) $v >= 20000 && (float) $v <= 60000) {
            // Excelの1900年うるう年バグに合わせ、1899-12-30 を起点にする。
            return Carbon::create(1899, 12, 30)->addDays((int) floor((float) $v))->format('Y-m-d');
        }

        // 年月日を数字で拾う（区切りは - / . 年月日）
        if (preg_match('/^(\d{4})\D+(\d{1,2})\D+(\d{1,2})/u', $v, $m)) {
            $y = (int) $m[1];
            $mo = (int) $m[2];
            $d = (int) $m[3];
            if (checkdate($mo, $d, $y)) {
                return sprintf('%04d-%02d-%02d', $y, $mo, $d);
            }
        }

        return '';   // 年が無い（7/20 など）は年を勘で補わない＝エラーにして人に直してもらう
    }

    /**
     * 時刻を 'H:i' に整える。読めない場合は空文字。
     * 受け付ける形：8:00／08:00／8時／Excelのシリアル値（0.3333…＝8:00）
     */
    public static function normalizeTime(string $value): string
    {
        $v = trim($value);
        if ($v === '') {
            return '';
        }

        // Excelの時刻＝1日を1とした小数（0.3333…＝8:00）
        if (preg_match('/^0?\.\d+$/', $v)) {
            $minutes = (int) round((float) $v * 24 * 60);
            // 四捨五入で 24:00 を超えないように丸める
            $minutes = max(0, min(23 * 60 + 59, $minutes));

            return sprintf('%d:%02d', intdiv($minutes, 60), $minutes % 60);
        }

        // 8:00／08:00／8:0
        if (preg_match('/^(\d{1,2})\s*[:：時]\s*(\d{1,2})?/u', $v, $m)) {
            $h = (int) $m[1];
            $i = isset($m[2]) && $m[2] !== '' ? (int) $m[2] : 0;
            if ($h <= 23 && $i <= 59) {
                return sprintf('%d:%02d', $h, $i);
            }
        }

        return '';
    }

    /** 見出し照合用の正規化（前後空白・空白・全角カッコ・記号ゆれを吸収）。 */
    private static function normKey(string $s): string
    {
        $s = trim($s);
        // 全角カッコ→半角、全角スペース・空白を除去
        $s = str_replace(['（', '）', '　'], ['(', ')', ''], $s);
        $s = preg_replace('/\s+/u', '', $s);
        // 「/」「・」「_」は無視（例：顧客名(代理店名) と 顧客名（代理店名）を同じに扱う）
        $s = str_replace(['/', '・', '_', '-'], '', $s);

        return mb_strtolower((string) $s);
    }
