    <h3>アサインのこと（アサイン担当）</h3>
    <ul>
      <li><b>アサインダッシュボード</b>：まずここを見て、今の状況をつかみます。数字カード（募集中の案件／今週の確定／希望0件の人／平均稼働率）と、<b>「気にかけたい人」</b>（希望を出しているのに入れていない人／連勤／稼働率30%未満／応募が多いのに選ばれていない人／しばらくアサインが無い人）。毎回目を通してください。</li>
      <li><b>スタッフ公開ボード</b>：<b>ここが公開の唯一の入口です。</b>
        <ol>
          <li>📣 お知らせ文を書く（スタッフ画面の一番上に出ます）</li>
          <li>🗓 締切日を入れる（表示だけ・過ぎても応募は受け付けます）</li>
          <li>案件ごとに「<b>公開する</b>」を押す（まとめて公開もできます）</li>
          <li>集合〜解散の時間を確認する（スタッフだけ集合時間が違う場合も、ここで変えて募集できます）</li>
          <li><b>📣 スタッフに伝えること</b>＝<b>備考のように自由に書ける1つの記入欄</b>です。書いた内容は<b>募集中（案件カードの備考）と確定後（確定アサインの詳細）の両方</b>で、スタッフの画面に表示されます（入力欄から離れると自動で保存）。<br>例）<i>前日設営があるため、8/29(土)15時集合です。帰宅予定は21時ごろです。大型の運動会です。</i></li>
        </ol>
        「👁 スタッフ画面を見る」で、スタッフにどう見えるかを確認できます。<b>非公開に戻すと、確定した案件もスタッフから見えなくなります。</b>
      </li>
      <li><b>経験回数</b>：<b>誰が、どのコンテンツ・どのポジションを、何回やったか</b>の一覧です。アサインを決めるときに
        「このコンテンツをやったことがある人は誰か」「このポジションに慣れているのは誰か」を探すために使います。<br>
        <b>拠点</b>・区分（社員／スタッフ）・名前で絞れます。タブは<b>人ごと</b>／<b>コンテンツから探す</b>／<b>ポジションから探す</b>の3つ。CSVでも落とせます。<br>
        <span class="why">※ 数えるのは<b>アサインが「確定」で、開催日がもう過ぎた案件</b>だけです。仮のアサイン・これからの案件・キャンセルは数えません。
        保存はしておらず開くたびに数え直すので、アサインを直せばここも自動で直ります。</span></li>
      <li><b>D決め（ディレクター）</b>：月次MTGで D・SD・FC を決める画面。社員名をクリック → 小窓で案件ごとに選びます。チップの色＝🟩緑：D・SD担当／🟦青：別の役割で稼働中／⬜グレー：空き。<b>保存ボタンはありません。押したその場で保存されます</b>（右上に「保存しました ○:○○」と出ます）。赤い「⚠ 保存できていません」が出たときだけ「保存し直す」を押してください。開催日が未入力の案件は保存できません。<br><b>月は上の ◀ ▶ で切り替えられます</b>（月名の横のカッコ＝その月の案件数）。最初に出るのは<b>今月</b>です。<b>SD は何人でも</b>付けられます（大型はコンテンツごとに2名いるため）。D は1案件1名です。</li>
      <li><b>日別ボード</b>：<b>ダブルブッキングに気づくための画面</b>です。同じ日の案件を横に並べて見ます（既定は今日から3週間分）。日付のヘッダーに「稼働可◯名／割当済◯名／残り◯名」が出て、<b>同じ日に重なった人は赤字＋⚠</b>。名前のそばの「今月 ◯/20」は月の件数（<b>上限20件</b>・到達で赤／残り2件で橙）。左がメンバー、右が希望者で、「＋」で追加、⚡で<b>自動アサイン</b>（条件に合う人をまとめて仮に入れます＝人は確認するだけ）。押した時点で保存されます。<br>
