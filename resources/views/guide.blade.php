      <li><b>エントリー新着（来た順）</b>：エントリーを<b>届いた順（新しいものが上）</b>に並べた画面です。<b>追加案件を出したあとに誰から手が挙がったか</b>、<b>🌱新人（入社1年未満）がどの案件に応募してくれたか</b>を追うのに使います。期間（直近7日／30日／90日／すべて）・追加案件のみ・新人のみで絞れます。まだアサインしていない応募は<b>未対応</b>と出るので、拾い漏れを防げます。見るだけの画面なので、入れるときは行の右「アサインへ →」から進みます。</li>
